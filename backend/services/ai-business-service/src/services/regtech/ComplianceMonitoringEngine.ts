  private async calculateTrendDirection(
    businessAccountId: string,
    metricName: string,
    currentValue: number
  ): Promise<string> {
    // Get historical values to determine trend
    const historicalData = await this.getHistoricalMetricValues(
      businessAccountId,
      metricName,
      7 // Last 7 days
    );
    
    if (historicalData.length < 2) return 'stable';
    
    const recentValues = historicalData.slice(-3); // Last 3 values
    const trend = recentValues[recentValues.length - 1] - recentValues[0];
    const threshold = Math.abs(currentValue) * 0.02; // 2% threshold
    
    if (trend > threshold) return 'improving';
    if (trend < -threshold) return 'deteriorating';
    return 'stable';
  }

