  private calculateTrendFromSeries(timeSeries: any[]): string {
    if (timeSeries.length < 2) return 'stable';
    
    const firstValue = timeSeries[0].value;
    const lastValue = timeSeries[timeSeries.length - 1].value;
    const change = (lastValue - firstValue) / firstValue * 100;
    
    if (Math.abs(change) < 2) return 'stable';
    return change > 0 ? 'improving' : 'deteriorating';
  }

  private calculateTrendStrength(timeSeries: any[]): number {
    if (timeSeries.length < 3) return 0;
    
    // Simple linear regression to calculate trend strength
    const n = timeSeries.length;
    const x = Array.from({ length: n }, (_, i) => i);
    const y = timeSeries.map(point => point.value);
    
    const sumX = x.reduce((a, b) => a + b, 0);
    const sumY = y.reduce((a, b) => a + b, 0);
    const sumXY = x.reduce((sum, xi, i) => sum + xi * y[i], 0);
    const sumX2 = x.reduce((sum, xi) => sum + xi * xi, 0);
    
    const slope = (n * sumXY - sumX * sumY) / (n * sumX2 - sumX * sumX);
    
    return Math.abs(slope) * 100; // Normalize to percentage
  }

  private async generateComplianceForecast(
    timeSeries: any[],
    days: number
  ): Promise<Array<{ date: Date; predictedValue: number; confidence: number }>> {
    // Simple linear forecast
    if (timeSeries.length < 2) return [];
    
    const values = timeSeries.map(point => point.value);
    const n = values.length;
    const x = Array.from({ length: n }, (_, i) => i);
    
    const sumX = x.reduce((a, b) => a + b, 0);
    const sumY = values.reduce((a, b) => a + b, 0);
    const sumXY = x.reduce((sum, xi, i) => sum + xi * values[i], 0);
    const sumX2 = x.reduce((sum, xi) => sum + xi * xi, 0);
    
    const slope = (n * sumXY - sumX * sumY) / (n * sumX2 - sumX * sumX);
    const intercept = (sumY - slope * sumX) / n;
    
    const forecast = [];
    const lastDate = new Date(timeSeries[timeSeries.length - 1].date);
    
    for (let i = 1; i <= days; i++) {
      const predictedValue = slope * (n + i - 1) + intercept;
      const confidence = Math.max(0, 100 - (i * 10)); // Decreasing confidence
      
      forecast.push({
        date: new Date(lastDate.getTime() + i * 24 * 60 * 60 * 1000),
        predictedValue,
        confidence
      });
    }
    
    return forecast;
  }

  // Automated Alert Generation
  async generateComplianceAlerts(businessAccountId: string): Promise<ComplianceAlert[]> {
    const alerts: ComplianceAlert[] = [];
    const metrics = await this.getComplianceMetrics(businessAccountId);
    
    // Generate alerts for critical compliance issues
    if (metrics.overallComplianceScore < 50) {
      const alert = await this.createComplianceAlert({
        businessAccountId,
        alertType: 'compliance_violation',
        severity: 'critical',
        title: 'Critical Compliance Score',
        description: `Overall compliance score is ${metrics.overallComplianceScore.toFixed(2)}%`,
        jurisdictionCode: 'ALL',
        currentValue: metrics.overallComplianceScore,
        thresholdValue: 80,
        alertData: {
          totalThresholds: metrics.totalThresholds,
          activeThresholds: metrics.activeThresholds,
          breachedMetrics: metrics.breachedMetrics
        },
        autoGenerated: true,
        createdBy: 'system'
      });
      alerts.push(alert);
    }
    
    // Generate alerts for individual threshold breaches
    const monitoring = await this.runComplianceMonitoring(businessAccountId);
    const criticalMonitoring = monitoring.filter(m => m.complianceStatus === 'critical' || m.complianceStatus === 'breach');
    
    for (const cm of criticalMonitoring) {
      const threshold = await this.getComplianceThreshold(cm.thresholdId);
      const alert = await this.createComplianceAlert({
        businessAccountId,
        alertType: 'threshold_breach',
        severity: cm.complianceStatus === 'breach' ? 'critical' : 'high',
        title: `Threshold Breach: ${threshold.thresholdName}`,
        description: `${threshold.metricName} has ${cm.complianceStatus} status`,
        jurisdictionCode: threshold.jurisdictionCode,
        thresholdId: threshold.id,
        metricName: threshold.metricName,
        currentValue: cm.currentValue,
        thresholdValue: cm.thresholdValue,
        alertData: {
          varianceAmount: cm.varianceAmount,
          variancePercentage: cm.variancePercentage,
          trendDirection: cm.trendDirection
        },
        autoGenerated: true,
        createdBy: 'system'
      });
      alerts.push(alert);
    }
    
    return alerts;
  }

  // Compliance Dashboard
  async getComplianceDashboard(businessAccountId: string, language: 'en' | 'ar' = 'en'): Promise<any> {
    const metrics = await this.getComplianceMetrics(businessAccountId);
    const recentAlerts = await this.getComplianceAlerts(businessAccountId, { limit: 10 });
    const activeThresholds = await this.getComplianceThresholds(businessAccountId, { isActive: true });
    
    return {
      summary: language === 'ar' ? {
        dashboardTitle: 'لوحة معلومات الامتثال',
        overallComplianceScore: metrics.overallComplianceScore,
        totalThresholds: metrics.totalThresholds,
        activeThresholds: metrics.activeThresholds,
        compliantMetrics: metrics.compliantMetrics,
        nonCompliantMetrics: metrics.activeThresholds - metrics.compliantMetrics,
        criticalAlerts: recentAlerts.filter(a => a.severity === 'critical').length,
        generatedAt: new Date().toISOString()
      } : {
        dashboardTitle: 'Compliance Dashboard',
        overallComplianceScore: metrics.overallComplianceScore,
        totalThresholds: metrics.totalThresholds,
        activeThresholds: metrics.activeThresholds,
        compliantMetrics: metrics.compliantMetrics,
        nonCompliantMetrics: metrics.activeThresholds - metrics.compliantMetrics,
        criticalAlerts: recentAlerts.filter(a => a.severity === 'critical').length,
        generatedAt: new Date().toISOString()
      },
      metrics,
      recentAlerts,
      activeThresholds,
      recommendations: this.generateComplianceRecommendations(metrics, recentAlerts, language)
    };
  }

  private generateComplianceRecommendations(
    metrics: ComplianceMetrics,
    alerts: ComplianceAlert[],
    language: 'en' | 'ar'
  ): string[] {
    const recommendations = [];
    
    if (metrics.overallComplianceScore < 80) {
      recommendations.push(language === 'ar' ? 
        'درجة الامتثال منخفضة - راجع جميع العتبات الحريرة' : 
        'Low compliance score - review all critical thresholds'
      );
    }
    
    if (metrics.breachedMetrics > 0) {
      recommendations.push(language === 'ar' ? 
        `هناك ${metrics.breachedMetrics} عتبات منتهكة - اتخذ إجراءات فورية` : 
        `${metrics.breachedMetrics} thresholds breached - take immediate action`
      );
    }
    
    const criticalAlerts = alerts.filter(a => a.severity === 'critical');
    if (criticalAlerts.length > 0) {
      recommendations.push(language === 'ar' ? 
        `هناك ${criticalAlerts.length} تنبيهات حريرة - أولوية عالية` : 
        `${criticalAlerts.length} critical alerts - high priority`
      );
    }
    
    return recommendations;
  }
