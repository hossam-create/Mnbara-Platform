  // Compliance Monitoring
  async monitorCompliance(
    businessAccountId: string,
    thresholdId: string,
    monitoringDate: Date = new Date()
  ): Promise<ComplianceMonitoring> {
    const threshold = await this.getComplianceThreshold(thresholdId);
    if (!threshold) {
      throw new Error('Threshold not found');
    }
    
    // Calculate current value based on threshold calculation method
    const currentValue = await this.calculateMetricValue(
      businessAccountId,
      threshold.metricName,
      threshold.calculationMethod
    );
    
    const varianceAmount = currentValue - (threshold.targetValue || 0);
    const variancePercentage = threshold.targetValue && threshold.targetValue !== 0 ? 
      (varianceAmount / threshold.targetValue) * 100 : 0;
    
    // Determine compliance status
    let complianceStatus: string = 'compliant';
    if (threshold.minimumValue && currentValue < threshold.minimumValue) {
      complianceStatus = 'breach';
    } else if (threshold.maximumValue && currentValue > threshold.maximumValue) {
      complianceStatus = 'breach';
    } else if (threshold.criticalThreshold && 
               (currentValue < threshold.criticalThreshold || currentValue > threshold.criticalThreshold)) {
      complianceStatus = 'critical';
    } else if (threshold.warningThreshold && 
               (currentValue < threshold.warningThreshold || currentValue > threshold.warningThreshold)) {
      complianceStatus = 'warning';
    }
    
    // Calculate trend direction
    const trendDirection = await this.calculateTrendDirection(
      businessAccountId,
      threshold.metricName,
      currentValue
    );
    
    const result = await prisma.$queryRaw`
      INSERT INTO compliance_monitoring (
        id,
        business_account_id,
        threshold_id,
        monitoring_date,
        current_value,
        threshold_value,
        variance_amount,
        variance_percentage,
        compliance_status,
        trend_direction,
        calculation_details,
        data_points,
        auto_calculated
      ) VALUES (
        ${uuidv4()}::uuid,
        ${businessAccountId}::uuid,
        ${thresholdId}::uuid,
        ${monitoringDate}::date,
        ${currentValue}::decimal,
        ${threshold.targetValue || 0}::decimal,
        ${varianceAmount}::decimal,
        ${variancePercentage}::decimal,
        ${complianceStatus}::varchar,
        ${trendDirection || null}::varchar,
        ${JSON.stringify({
          thresholdName: threshold.thresholdName,
          calculationMethod: threshold.calculationMethod,
          regulatoryReference: threshold.regulatoryReference
        })}::jsonb,
        '[]'::jsonb,
        true::boolean
      ) RETURNING id
    `;
    
    const monitoringId = (result as any)[0]?.id;
    return this.getComplianceMonitoring(monitoringId);
  }

