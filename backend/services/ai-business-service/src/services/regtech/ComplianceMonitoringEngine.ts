  // Automated Compliance Monitoring
  async runComplianceMonitoring(businessAccountId: string): Promise<ComplianceMonitoring[]> {
    const thresholds = await this.getComplianceThresholds(businessAccountId, { isActive: true });
    const monitoringResults: ComplianceMonitoring[] = [];
    
    for (const threshold of thresholds) {
      try {
        const monitoring = await this.monitorCompliance(businessAccountId, threshold.id);
        monitoringResults.push(monitoring);
        
        // Create alert if non-compliant
        if (monitoring.complianceStatus !== 'compliant') {
          await this.createComplianceAlert({
            businessAccountId,
            alertType: 'threshold_breach',
            severity: monitoring.complianceStatus === 'breach' ? 'critical' : 'high',
            title: `Compliance Threshold Breach: ${threshold.thresholdName}`,
            description: `${threshold.metricName} threshold breached. Current value: ${monitoring.currentValue}, Threshold: ${monitoring.thresholdValue}`,
            jurisdictionCode: threshold.jurisdictionCode,
            thresholdId: threshold.id,
            metricName: threshold.metricName,
            currentValue: monitoring.currentValue,
            thresholdValue: monitoring.thresholdValue,
            alertData: {
              thresholdName: threshold.thresholdName,
              calculationMethod: threshold.calculationMethod,
              varianceAmount: monitoring.varianceAmount,
              variancePercentage: monitoring.variancePercentage
            },
            autoGenerated: true,
            createdBy: 'system'
          });
        }
      } catch (error) {
        console.error(`Error monitoring threshold ${threshold.id}:`, error);
      }
    }
    
    return monitoringResults;
  }

  // Compliance Analytics
  async getComplianceMetrics(businessAccountId: string): Promise<ComplianceMetrics> {
    const thresholds = await this.getComplianceThresholds(businessAccountId);
    const activeThresholds = thresholds.filter(t => t.isActive);
    
    // Get current compliance status for all active thresholds
    const today = new Date();
    const currentMonitoring: ComplianceMonitoring[] = [];
    
    for (const threshold of activeThresholds) {
      try {
        const monitoring = await this.monitorCompliance(businessAccountId, threshold.id, today);
        currentMonitoring.push(monitoring);
      } catch (error) {
        console.error(`Error getting current monitoring for threshold ${threshold.id}:`, error);
      }
    }
    
    const compliantMetrics = currentMonitoring.filter(m => m.complianceStatus === 'compliant').length;
    const warningMetrics = currentMonitoring.filter(m => m.complianceStatus === 'warning').length;
    const criticalMetrics = currentMonitoring.filter(m => m.complianceStatus === 'critical').length;
    const breachedMetrics = currentMonitoring.filter(m => m.complianceStatus === 'breach').length;
    
    const overallComplianceScore = activeThresholds.length > 0 ? 
      (compliantMetrics / activeThresholds.length) * 100 : 100;
    
    return {
      businessAccountId,
      jurisdictionCode: 'ALL', // Aggregate across all jurisdictions
      totalThresholds: thresholds.length,
      activeThresholds: activeThresholds.length,
      compliantMetrics,
      warningMetrics,
      criticalMetrics,
      breachedMetrics,
      overallComplianceScore,
      lastUpdated: new Date()
    };
  }

  async getComplianceTrends(
    businessAccountId: string,
    metricName: string,
    jurisdictionCode: string,
    days: number = 90
  ): Promise<ComplianceTrend> {
    const threshold = await this.getComplianceThresholds(businessAccountId, {
      metricName,
      jurisdictionCode,
      limit: 1
    });
    
    if (threshold.length === 0) {
      throw new Error('No threshold found for the specified metric and jurisdiction');
    }
    
    const monitoringHistory = await this.getComplianceMonitoringHistory(
      businessAccountId,
      threshold[0].id,
      days
    );
    
    const timeSeries = monitoringHistory.map(m => ({
      date: m.monitoringDate,
      value: m.currentValue,
      threshold: m.thresholdValue,
      complianceStatus: m.complianceStatus
    }));
    
    const trendDirection = this.calculateTrendFromSeries(timeSeries);
    const trendStrength = this.calculateTrendStrength(timeSeries);
    const forecast = await this.generateComplianceForecast(timeSeries, 7);
    
    return {
      metricName,
      jurisdictionCode,
      timeSeries,
      trendDirection,
      trendStrength,
      forecast
    };
  }

